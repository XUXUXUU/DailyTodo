import Foundation

@main enum FeishuAutomationTests {
    static func main() throws {
        var count=0
        func check(_ value:Bool,_ name:String) { precondition(value,name);count += 1;print("PASS:",name) }
        var startup=FeishuStartupReadiness(existingPIDs:[])
        func candidate(_ pid:Int32,_ active:Bool=true,_ ready:Bool=true)->FeishuStartupCandidate {
            FeishuStartupCandidate(pid:pid,finished:true,active:active,ready:ready)
        }
        check(startup.sample([],at:0) == .wait,"飞书未启动时等待，不误用旧进程")
        check(startup.sample([candidate(10,true,false)],at:1) == .wait,"启动进程没有聊天界面时不能开始自动化")
        check(startup.sample([],at:2) == .wait,"启动进程退出交接时继续等待")
        check(startup.sample([candidate(20,false)],at:3) == .activate(20),"交接后激活真正的新进程")
        check(startup.sample([candidate(20)],at:3.2) == .wait,"新窗口需稳定后才可操作")
        check(startup.sample([candidate(20)],at:5.3) == .ready(20),"自动化使用交接后的进程")
        var multiple=FeishuStartupReadiness(existingPIDs:[])
        check(multiple.sample([candidate(1),candidate(2)],at:0) == .wait,"多个同身份进程不随机选择")
        var changed=FeishuStartupReadiness(existingPIDs:[])
        _ = changed.sample([candidate(1)],at:0)
        check(changed.sample([candidate(2)],at:1.9) == .wait,"更换进程会重置就绪计时")
        check(changed.sample([candidate(2)],at:4) == .ready(2),"新进程独立完成稳定检测")
        var warm=FeishuStartupReadiness(existingPIDs:[3])
        _ = warm.sample([candidate(3)],at:0)
        check(warm.sample([candidate(3)],at:0.6) == .ready(3),"已运行飞书无需完整冷启动等待")
        var focus=FeishuStartupReadiness(existingPIDs:[])
        _ = focus.sample([candidate(4)],at:0)
        check(focus.sample([candidate(4,false)],at:0.3) == .foregroundLost,"界面就绪后用户切走即停止，不反复抢焦点")
        var activation=FeishuStartupReadiness(existingPIDs:[])
        _ = activation.sample([candidate(5,false)],at:0)
        check(activation.sample([candidate(5,false)],at:0.3) == .wait,"同一进程只请求激活一次")
        check(activation.sample([candidate(5,false)],at:2.1) == .foregroundLost,"激活未成功时明确停止")
        var earlyFocus=FeishuStartupReadiness(existingPIDs:[])
        _ = earlyFocus.sample([candidate(6,true,false)],at:0)
        _ = earlyFocus.sample([candidate(6,false,false)],at:0.3)
        check(earlyFocus.sample([candidate(6,false,true)],at:5) == .foregroundLost,"就绪前切走不能稍后重新抢焦点")
        var interrupted=FeishuStartupReadiness(existingPIDs:[])
        check(interrupted.sample([],at:0,interrupted:true) == .foregroundLost,"等待期间用户切走即终止请求")
        check(interrupted.sample([candidate(9)],at:5) == .foregroundLost,"更换进程不能清除用户中断")
        var handoff=FeishuStartupReadiness(existingPIDs:[])
        _ = handoff.sample([candidate(1,true,false)],at:0)
        _ = handoff.sample([candidate(1,false,false)],at:0.1)
        _ = handoff.sample([],at:0.2)
        check(handoff.sample([candidate(2,false)],at:0.3) == .activate(2),"真实进程退出交接仍可激活新进程")
        // A document before the sidebar used to exhaust the depth-first budget.
        final class Fixture {
            let name:String;let role:String;let url:String
            var children:[Fixture]
            init(_ name:String,role:String="AXGroup",url:String="",_ children:[Fixture]=[]) {self.name=name;self.role=role;self.url=url;self.children=children}
        }
        let document=Fixture("document",role:"AXWebArea",url:"https://example.feishu.cn/wiki/private",(0..<1800).map {Fixture("private-document-\($0)")})
        let history=Fixture("history",role:"AXGroup",url:"",(0..<1800).map {Fixture("old-message-\($0)")})
        let chat=Fixture("messenger-chat",role:"AXWebArea",url:"file:///messenger/messenger-chat/zh-CN.html",[history,Fixture("composer",role:"AXTextArea")])
        let root=Fixture("window",role:"AXGroup",url:"",[document,chat,Fixture("sidebar",role:"AXGroup",url:"",[Fixture("avatar",role:"AXButton"),Fixture("search",role:"AXButton")])])
        var observed:[String]=[]
        let bounded = FeishuAXTraversal.build(root:root,limit:20,maxDepth:35,makeNode:{ node in observed.append(node.name);return node },children:{$0.children},shouldExpand:{FeishuAXTraversal.shouldExpand(role:$0.role,label:$0.name,url:$0.url)},appendChild:{_,_ in})
        check(observed.contains("avatar") && observed.contains("search"),"长文档不能耗尽额度导致头像和搜索入口消失")
        check(observed.contains("composer"),"深层历史不能遮蔽同级聊天输入框")
        check(!observed.contains(where:{$0.hasPrefix("private-document-")}),"不读取无关文档正文")
        check(observed.count==20,"AX遍历严格限制节点数量")
        check(!bounded.complete,"不完整树不能用于判断空草稿或缺少附件")
        let opaque=FeishuAXTraversal.build(root:document,limit:20,maxDepth:35,makeNode:{$0},children:{$0.children},shouldExpand:{FeishuAXTraversal.shouldExpand(role:$0.role,label:$0.name,url:$0.url)},appendChild:{_,_ in})
        check(opaque.complete,"明确排除的云文档不算不安全截断")
        let exact=FeishuAXTraversal.build(root:Fixture("small",role:"AXGroup",url:"",[Fixture("leaf")]),limit:2,maxDepth:1,makeNode:{$0},children:{$0.children},shouldExpand:{_ in true},appendChild:{_,_ in})
        check(exact.complete,"正好到达节点上限但没有遗漏仍完整")

        check(FeishuAXTraversal.shouldExpand(role:"AXWebArea",label:"ternantCardModal",url:""),"账号卡片允许读取")
        check(FeishuAXTraversal.shouldExpand(role:"AXWebArea",label:"search-command-bar",url:""),"搜索面板允许读取")
        check(!FeishuAXTraversal.shouldExpand(role:"AXWebArea",label:"messenger",url:"file:///messenger/messenger/zh-CN.html"),"消息列表不消耗聊天与原生控件预算")
        var depths:[String]=[]
        let shallow = FeishuAXTraversal.build(root:root,limit:100,maxDepth:1,makeNode:{depths.append($0.name);return $0},children:{$0.children},shouldExpand:{_ in true},appendChild:{_,_ in})
        check(depths.count==4 && !depths.contains("avatar"),"遍历仍遵守最大深度")
        check(!shallow.complete,"深度截断必须被识别，不能把深层附件当不存在")
        let suite="DailyTodo.FeishuTest."+UUID().uuidString
        let prefs=UserDefaults(suiteName:suite)!
        defer { prefs.removePersistentDomain(forName:suite) }
        prefs.set(true,forKey:"openFeishuAfterCopy")
        var config=FeishuAutomationConfiguration.load(from:prefs)
        check(!config.enabled && config.mode == .draft,"旧唤起权限不升级为自动发送")
        config.enabled=true;config.recipient="  测试收件人  ";config.mode = .send
        try config.save(to:prefs)
        let loaded=FeishuAutomationConfiguration.load(from:prefs)
        check(loaded.enabled && loaded.recipient == "测试收件人" && loaded.mode == .send,"完整配置重建后保持")
        check(loaded.buttonTitle == "一键转发","按钮不随联系人姓名变化")
        check(FeishuAutomationConfiguration().buttonTitle == "复制全部","关闭转发显示复制全部")
        var invalid=loaded;invalid.recipient="\n"
        check((try? invalid.save(to:prefs)) == nil,"空收件人不能覆盖有效配置")
        check(FeishuAutomationConfiguration.load(from:prefs).recipient == "测试收件人","验证失败保留原设置")
        let migrated=loaded.productionSafe
        check(!migrated.enabled && migrated.recipient == "何雪瑶" && !migrated.recipientIsSelf,"旧自定义收件人关闭后迁移，不能静默改发瑶总")
        var official=FeishuAutomationConfiguration();official.enabled=true
        check(official.productionSafe.enabled && official.productionSafe.recipient == "何雪瑶","正式收件人固定且保留有效开关")
        official.recipientIsSelf=true
        check(!official.productionSafe.enabled,"旧本人测试不能迁移为正式发送")
        check(FeishuDeliveryMode.draft.title == "填入聊天框","只填写模式名称必须准确")
        check(FeishuAutomationRules.selfName(profileTexts:[]) == nil,"账号卡片内容未加载时必须继续等待")
        check(FeishuAutomationRules.selfName(profileTexts:["安龙","润泽园教育","我的个人名片 我的二维码与链接","设置 退出登录"]) == "安龙","从当前飞书账号卡片识别姓名")
        check(FeishuAutomationRules.selfName(profileTexts:["何雪瑶","消息","发送给何雪瑶"]) == nil,"普通聊天不可当作本人身份")
        check(FeishuAutomationRules.selfName(profileTexts:["","润泽园教育","我的个人名片","退出登录"]) == nil,"没有账号姓名则停止测试")
        check(FeishuAutomationRules.isVerifiedSelfComposer("可以向自己发送文件或转发消息\u{200b}\n",editableText:false),"本人专用输入区才能进行自测")
        check(!FeishuAutomationRules.isVerifiedSelfComposer("发送给安龙",editableText:false),"同名他人的聊天不能冒充本人")
        check(!FeishuAutomationRules.isVerifiedSelfComposer("可以向自己发送文件或转发消息",editableText:true),"真实草稿不能冒充本人空输入区")
        var approval=FeishuAutomationConfiguration();approval.enabled=true
        check(approval.canDispatch(selfTest:false),"开启后可以填写聊天框，无需应用内二次确认")
        check(approval.deliveryMode(selfTest:false) == .draft,"普通转发保持只填写，不能暗中升级自动发送")
        check(approval.deliveryMode(selfTest:true) == .draft,"本人填写测试不能暗中升级为自动发送")
        check(approval.deliveryMode(selfTest:true,testMode:.send) == .send,"未保存的自动发送选择应用于本人测试")
        check(approval.deliveryMode(selfTest:false,testMode:.send) == .draft,"测试覆盖参数不能改变正式转发方式")
        check(approval.summary == "填入聊天框","完成页显示填写方式")
        var sendSummary=approval;sendSummary.mode = .send
        check(sendSummary.summary == "自动发送","完成页显示自动发送方式")
        approval.enabled=false
        check(approval.summary == "关闭","未开启必须显示关闭")
        check(!approval.canDispatch(selfTest:false),"关闭功能不可操作飞书")
        check(approval.canDispatch(selfTest:true),"显式本人测试不依赖正式开关")
        check(!FeishuAutomationRules.isEmptyComposer("发送给安龙",name:"安龙",isSelf:true,readable:true,editableText:false),"最终粘贴前仍拒绝同名他人输入区")
        check(!FeishuAutomationRules.isEmptyComposer("",name:"安龙",isSelf:true,readable:true,editableText:false),"最终粘贴前没有本人标记必须停止")
        check(FeishuAutomationRules.selfName(profileTexts:["润泽园教育","已认证","我的个人名片","退出登录"]) == nil,"组织名先加载时不得当作本人姓名")
        var ready=FeishuProfileReadiness()
        let profile=["安龙","润泽园教育","我的个人名片","退出登录"]
        check(ready.sample(texts:profile,nodeCount:42,at:0) == nil,"账号卡片首次成形仍等待稳定")
        check(ready.sample(texts:profile,nodeCount:42,at:0.2) == nil,"短暂可见不足以判断账号加载完成")
        check(ready.sample(texts:profile,nodeCount:42,at:0.7) == "安龙","内容和结构稳定后才识别本人")
        check(ready.sample(texts:["他人","组织","我的个人名片","退出登录"],nodeCount:42,at:0.8) == nil,"账号内容变化必须重新等待")
        check(ready.sample(texts:[],nodeCount:0,at:0.9) == nil,"账号卡片消失会清空稳定性计时")
        check(ready.sample(texts:profile,nodeCount:42,at:2) == nil,"卡片重新出现不能沿用旧稳定计时")
        check(FeishuAutomationRules.normalized("\u{200b} \n\u{feff}").isEmpty,"空编辑器零宽字符不算草稿")
        check(FeishuAutomationRules.recipientMatches("发送给 测试收件人",name:"测试收件人",isSelf:false),"准确聊天输入区")
        check(!FeishuAutomationRules.recipientMatches("发送给 测试收件人助理",name:"测试收件人",isSelf:false),"相似姓名不能通过核对")
        check(!FeishuAutomationRules.recipientMatches("可以向自己发送文件或转发消息",name:"其他人",isSelf:false),"自己输入区不能冒充其他联系人")
        check(FeishuAutomationRules.recipientMatches("可以向自己发送文件或转发消息",name:"安龙",isSelf:true),"明确自己联系人允许专用输入区")
        check(FeishuAutomationRules.canSendUsingReturn(hint:"Shift + Enter 换行"),"识别实际发送键")
        check(!FeishuAutomationRules.canSendUsingReturn(hint:"Enter 换行"),"不猜测未知发送键")
        check(!FeishuAutomationRules.canSendUsingReturn(hint:""),"无键位线索不发送")
        check(FeishuAutomationRules.isEmptyDraft("\u{200b}\n"),"空草稿可填写")
        check(!FeishuAutomationRules.isEmptyDraft("未完成的消息"),"保留已有草稿")
        check(FeishuAutomationRules.uniqueExactMatch(["测试收件人","测试收件人助理"],name:"测试收件人") == 0,"联系人只接受精确姓名")
        check(FeishuAutomationRules.uniqueExactMatch(["测试收件人","测试收件人"],name:"测试收件人") == nil,"同名联系人阻止自动选择")
        check(FeishuAutomationRules.uniqueExactMatch(["其他人"],name:"测试收件人") == nil,"无匹配联系人不回退首项")
        check(FeishuAutomationRules.mayFill(header:"测试收件人",description:"发送给 测试收件人",name:"测试收件人",isSelf:false,draft:"",focused:true),"现场空输入区允许写入")
        check(!FeishuAutomationRules.mayFill(header:"测试收件人",description:"发送给 测试收件人",name:"测试收件人",isSelf:false,draft:"刚输入的新草稿",focused:true),"聚焦期间新输入草稿不能覆盖")
        check(!FeishuAutomationRules.mayFill(header:"其他人",description:"发送给 测试收件人",name:"测试收件人",isSelf:false,draft:"",focused:true),"消息正文姓名不代替聊天标题")
        check(!FeishuAutomationRules.mayFill(header:"测试收件人",description:"发送给 测试收件人",name:"测试收件人",isSelf:false,draft:"",focused:false),"失去当前输入焦点不写入")
        check(!FeishuAutomationRules.mayFill(header:"测试收件人",description:"发送给 测试收件人",name:"测试收件人",isSelf:false,draft:"",focused:true,readable:false),"读不到草稿不能当作空草稿")
        check(FeishuAutomationRules.isEmptyComposer("可以向自己发送文件或转发消息\u{200b}\n",name:"安龙",isSelf:true,readable:true,editableText:false),"只读占位提示不是正文")
        check(!FeishuAutomationRules.isEmptyComposer("可以向自己发送文件或转发消息\u{200b}\n",name:"安龙",isSelf:true,readable:true,editableText:true),"用户真的输入占位词也必须保留")
        check(!FeishuAutomationRules.isEmptyComposer("发送给其他人",name:"目标",isSelf:false,readable:true,editableText:false),"其他人的占位提示不能通过核对")
        check(!FeishuAutomationRules.isEmptyComposer("",name:"目标",isSelf:false,readable:false,editableText:false),"读不到输入区不能继续")
        let dir=FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer {try? FileManager.default.removeItem(at:dir)}
        let ledger=FeishuDeliveryLedger(directory:dir)
        let id=FeishuDeliveryLedger.fingerprint(recipient:"A",day:"2026-11-06",text:"正文一")
        check(try !ledger.hasAttempt(id),"未发送内容可在操作聊天前检查")
        check(try ledger.claim(id),"首次发送原子占位")
        check(try ledger.hasAttempt(id),"操作聊天前识别重复内容")
        check(try !ledger.claim(id),"未确认发送禁止重试")
        check(try !FeishuDeliveryLedger(directory:dir).claim(id),"重启后仍阻止重复发送")
        try ledger.finish(id,sent:true)
        check(try !ledger.claim(id),"已发送正文禁止重复")
        check(try ledger.claim(FeishuDeliveryLedger.fingerprint(recipient:"A",day:"2026-11-06",text:"正文二")),"修改正文允许新发送")
        check(try ledger.claim(FeishuDeliveryLedger.fingerprint(recipient:"B",day:"2026-11-06",text:"正文一")),"不同收件人独立去重")
        check(try ledger.claim(FeishuDeliveryLedger.fingerprint(recipient:"A",day:"2026-11-09",text:"正文一")),"下一工作日不受旧发送影响")
        try Data("broken".utf8).write(to:dir.appendingPathComponent("feishu-deliveries.json"))
        check((try? ledger.claim("another")) == nil,"损坏账本停止发送而非清空去重")
        print("FEISHU TOTAL:",count)
    }
}

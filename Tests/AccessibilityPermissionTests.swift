import Foundation

@main enum AccessibilityPermissionTests {
    static func main() {
        var count=0
        func check(_ value:Bool,_ name:String) {precondition(value,name);count += 1;print("PASS:",name)}
        check(AccessibilityPermissionStatus.evaluate(current:false,fresh:nil) == .checking,"未完成真实检测不能解锁")
        check(AccessibilityPermissionStatus.evaluate(current:false,fresh:false) == .notGranted,"旧签名开关不能冒充当前授权")
        check(AccessibilityPermissionStatus.evaluate(current:false,fresh:true) == .restartRequired,"新进程允许但旧进程未生效提示重启")
        check(AccessibilityPermissionStatus.evaluate(current:true,fresh:true) == .allowed,"两次真实检查均允许才解锁")
        check(AccessibilityPermissionStatus.evaluate(current:true,fresh:false) == .notGranted,"撤销后的旧进程缓存不能冒充授权")
        check(!AccessibilityPermissionStatus.restartRequired.ready,"待重启不提前启用功能")
        check(!AccessibilityPermissionStatus.checking.ready,"检测过程中不能发送")
        check(AccessibilityPermissionStatus.allowed.ready,"确认授权后允许设置和测试")
        check(AccessibilityPermissionStatus.evaluate(current:false,fresh:false,access:.allowed) == .notGranted,"撤销后仍可读取的旧连接不能冒充当前授权")
        check(AccessibilityPermissionStatus.evaluate(current:false,fresh:nil,access:.allowed) == .checking,"旧连接可读但未完成新进程校验不能启用")
        check(AccessibilityPermissionStatus.evaluate(current:true,fresh:false,access:.denied) == .notGranted,"实际API禁用不能被旧true缓存冒充")
        check(AccessibilityPermissionStatus.evaluate(current:false,fresh:true,access:.denied) == .restartRequired,"当前API禁用但新进程允许需重启")
        check(AccessibilityPermissionStatus.evaluate(current:false,fresh:nil,access:.unknown) == .checking,"IPC未知错误不能假装获得权限")
        check(AccessibilityGuideForeground.isSetup(bundleIdentifier:"com.apple.finder",isOwnApp:false),"访达是拖拽授权流程的一部分，助手不能消失")
        check(AccessibilityGuideForeground.isSetup(bundleIdentifier:"com.apple.systempreferences",isOwnApp:false),"系统设置保持引导可见")
        check(AccessibilityGuideForeground.isSetup(bundleIdentifier:nil,isOwnApp:true),"自己的设置页保持引导可见")
        check(!AccessibilityGuideForeground.isSetup(bundleIdentifier:"com.electron.lark",isOwnApp:false),"其他应用不显示助手或抢回焦点")
        check(AccessibilityAccessVerdict.combining([.denied,.allowed]) == .allowed,"单个受限窗口不能否决另一个进程的真实访问成功")
        check(AccessibilityAccessVerdict.combining([.allowed,.denied]) == .allowed,"权限综合判断不依赖窗口顺序")
        check(AccessibilityAccessVerdict.combining([.unknown,.denied]) == .denied,"没有任何实际允许时保留拒绝结果")
        check(AccessibilityAccessVerdict.combining([.unknown]) == .unknown,"未知不能冒充允许")
        check(AccessibilityAccessVerdict.combining([]) == .unknown,"无探测对象不能冒充允许")
        check(AccessibilityPermissionStatus.evaluate(current:false,fresh:true,access:.allowed) == .restartRequired,"新进程已获授权但当前进程未刷新时引导重启")
        check(AccessibilityPermissionStatus.evaluate(current:true,fresh:false,access:.allowed) == .notGranted,"当前旧缓存可用但新进程已撤销时必须禁用")
        check(AccessibilityPermissionStatus.evaluate(current:true,fresh:true,access:.allowed) == .allowed,"新旧进程获权且实际访问成功才能正常启用")
        var session=AccessibilityPermissionSession()
        check(session.evaluate(main:true,worker:false,fresh:true,access:.allowed) == .restartRequired,"后台连接未刷新不能显示已就绪")
        check(session.evaluate(main:true,worker:true,fresh:true,access:.allowed) == .restartRequired,"同进程待重启状态不在定时检测时反复闪动")
        check(session.evaluate(main:false,worker:false,fresh:false,access:.allowed) == .notGranted,"待重启也不能掩盖用户撤销权限")
        var relaunched=AccessibilityPermissionSession()
        check(relaunched.evaluate(main:true,worker:true,fresh:true,access:.allowed) == .allowed,"新进程授权完整即可恢复")
        relaunched.requireRestart()
        check(relaunched.evaluate(main:true,worker:true,fresh:true,access:.allowed) == .restartRequired,"执行入口连接失效可明确要求重启")
        var targetSession=AccessibilityPermissionSession()
        check(targetSession.evaluate(main:true,worker:true,fresh:true,access:.allowed,target:.denied) == .restartRequired,"飞书连接拒绝时其他进程允许不能提前解锁转发")
        var absentTarget=AccessibilityPermissionSession()
        check(absentTarget.evaluate(main:true,worker:true,fresh:true,access:.allowed,target:.unknown) == .allowed,"尚未启动飞书不妨碍完成系统授权")
        let gate=AccessibilityAuthorizationGate()
        check(!gate.permits(at:0),"后台授权快照默认不允许")
        gate.confirm(ready:true,at:10)
        check(gate.permits(at:11),"后台操作使用刚核对的授权快照")
        check(!gate.permits(at:17),"主线程停止更新后旧授权快照自动失效")
        gate.confirm(ready:false,at:12)
        check(!gate.permits(at:12),"撤销状态立即传递给后台操作")
        var guide=AccessibilityGuideContinuation()
        check(guide.take(ready:true,setupOwnsFocus:true) == .none,"未打开助手时不能自动抢焦点")
        guide.begin()
        check(guide.take(ready:false,setupOwnsFocus:true) == .none,"尚未实际授权不能结束助手")
        check(guide.take(ready:true,setupOwnsFocus:true) == .returnToApp,"授权成功且仍在设置流程时自动返回")
        check(guide.take(ready:true,setupOwnsFocus:true) == .none,"同一次授权只返回一次")
        guide.begin()
        check(guide.take(ready:true,setupOwnsFocus:false) == .closeQuietly,"已去其他应用时只收起助手")
        check(guide.take(ready:true,setupOwnsFocus:true) == .none,"安静关闭后不会延迟抢回焦点")
        guide.begin();guide.cancel()
        check(guide.take(ready:true,setupOwnsFocus:true) == .none,"手动关闭取消后续自动返回")
        guide.begin()
        check(guide.take(ready:true,setupOwnsFocus:true) == .returnToApp,"重新打开助手可开始新的单次续接")
        print("PERMISSION TOTAL:",count)
    }
}
